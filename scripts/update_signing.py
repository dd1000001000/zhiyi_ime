"""Signs the release manifests (see update/include/cxxime/update.h).

  python scripts/update_signing.py generate                 # make a signing key
  python scripts/update_signing.py generate --write-inc      # ... and write the public key in
  python scripts/update_signing.py sign latest.json [...]    # write <manifest>.sig for each

`generate` creates an ECDSA P-256 private key (PEM) and prints the public key in the form
update_public_key.inc expects: base64 of X || Y (32 + 32 bytes). Keep the private key off the
repository — only a release machine needs it.

`sign` writes, next to each manifest, a `.sig` file: base64 of the raw signature r || s (64
bytes), over the manifest's exact bytes, which is what verify_signature() checks.

Needs the `cryptography` package (pip install cryptography).
"""
import argparse
import base64
import os
import sys

try:
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
except ImportError:  # pragma: no cover - a clear message beats a traceback
    print("this script needs the 'cryptography' package: pip install cryptography", file=sys.stderr)
    raise SystemExit(2)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_KEY = os.path.join(ROOT, "update-signing-key.pem")
INC_PATH = os.path.join(ROOT, "update", "src", "update_public_key.inc")


def generate(key_path, write_inc):
    if os.path.exists(key_path):
        print(f"{key_path} already exists; refusing to overwrite it", file=sys.stderr)
        return 1
    key = ec.generate_private_key(ec.SECP256R1())
    with open(key_path, "wb") as out:
        out.write(key.private_bytes(serialization.Encoding.PEM,
                                    serialization.PrivateFormat.PKCS8,
                                    serialization.NoEncryption()))
    numbers = key.public_key().public_numbers()
    raw = numbers.x.to_bytes(32, "big") + numbers.y.to_bytes(32, "big")
    public_b64 = base64.b64encode(raw).decode()
    print(f"private key written to {key_path}  (keep it OFF the repository)")
    print("public key (base64, X || Y):")
    print(public_b64)
    if write_inc:
        with open(INC_PATH, "w", encoding="utf-8") as out:
            out.write("// Generated by scripts/update_signing.py: the public half of the update signing key\n")
            out.write("// (ECDSA P-256, X || Y, base64). Replace only together with a release installed by hand.\n")
            out.write(f'"{public_b64}"\n')
        print(f"wrote {INC_PATH}")
    return 0


def _der_to_raw(der):
    """A DER SEQUENCE of two INTEGERs -> the 64-byte r || s verify_signature() expects."""
    if len(der) < 8 or der[0] != 0x30:
        raise ValueError("unexpected signature encoding")
    index = 2 if der[1] < 0x80 else 2 + (der[1] & 0x7F)
    values = []
    for _ in range(2):
        if der[index] != 0x02:
            raise ValueError("unexpected signature encoding")
        length = der[index + 1]
        value = der[index + 2:index + 2 + length]
        index += 2 + length
        values.append(value.lstrip(b"\x00").rjust(32, b"\x00"))
    return values[0] + values[1]


def sign(key_path, manifests):
    with open(key_path, "rb") as key_file:
        key = serialization.load_pem_private_key(key_file.read(), password=None)
    for manifest in manifests:
        with open(manifest, "rb") as manifest_file:
            data = manifest_file.read()
        signature = base64.b64encode(_der_to_raw(key.sign(data, ec.ECDSA(hashes.SHA256()))))
        out_path = manifest + ".sig"
        with open(out_path, "wb") as out:
            out.write(signature + b"\n")
        print(f"{manifest} -> {out_path}")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Sign zhiyi_ime release manifests (ECDSA P-256).")
    sub = parser.add_subparsers(dest="command", required=True)

    generate_parser = sub.add_parser("generate", help="create a signing key")
    generate_parser.add_argument("--key", default=DEFAULT_KEY)
    generate_parser.add_argument("--write-inc", action="store_true",
                                 help="write update/src/update_public_key.inc")
    sign_parser = sub.add_parser("sign", help="write <manifest>.sig for each manifest")
    sign_parser.add_argument("--key", default=DEFAULT_KEY)
    sign_parser.add_argument("manifests", nargs="+")

    args = parser.parse_args()
    if args.command == "generate":
        return generate(args.key, args.write_inc)
    return sign(args.key, args.manifests)


if __name__ == "__main__":
    sys.exit(main())
